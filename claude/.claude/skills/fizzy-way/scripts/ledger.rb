#!/usr/bin/env ruby
# Tracks check.rb's findings over time in overlays/<repo>.ledger.yml, so each run reports
# what's new and what got fixed instead of everything again, and ranks what to fix next.
#
#   ledger.rb [ROOT]             update the ledger; print new, fixed, and open counts
#   ledger.rb [ROOT] --next [N]  open findings ranked, grouped into the next theme to take on
#
# Accepted divergences live in overlays/<repo>.yml and never reach the ledger.

require_relative "check"
require "date"

# How much fixing one finding moves the codebase toward Fizzy's shape.
WEIGHTS = {
  "service-layer" => 3, "unorganized-model" => 3, "state-columns" => 3,
  "custom-action" => 2, "silent-persistence" => 2,
  "custom-route" => 1, "route-restriction" => 1, "fat-job" => 1,
  "anemic-method" => 1, "anemic-concern" => 1, "anemic-partial" => 1
}.freeze

class Ledger
  attr_reader :repo, :entries

  def initialize(repo)
    @repo = repo
    @entries = path.exist? ? YAML.load_file(path).fetch("findings", {}) : {}
  end

  def path
    repo.overlay(".ledger.yml")
  end

  # Returns the ids that are new, reopened, and fixed since the last run.
  def record(findings, on: Date.today.iso8601)
    current = findings.to_h { [ it.id, it ] }
    changes = { new: [], reopened: [], fixed: [] }

    current.each do |id, finding|
      entry = entries[id]

      if entry.nil?
        changes[:new] << id
        entries[id] = { "check" => finding.check.name, "path" => finding.path, "message" => finding.message, "status" => "open", "first_seen" => on }
      elsif entry["status"] == "fixed"
        changes[:reopened] << id
        entry.merge!("status" => "open", "reopened_on" => on).delete("fixed_on")
      end

      entries[id]["message"] = finding.message
    end

    entries.each do |id, entry|
      if entry["status"] == "open" && !current.key?(id)
        changes[:fixed] << id
        entry.merge!("status" => "fixed", "fixed_on" => on)
      end
    end

    changes
  end

  def open
    entries.select { _2["status"] == "open" }
  end

  def save
    header = "# Generated by scripts/ledger.rb. Status per finding id: open or fixed.\n" \
      "# Accept a finding on purpose in #{repo.toplevel.basename}.yml instead of editing it here.\n"
    path.write(header + { "findings" => entries.sort.to_h }.to_yaml)
  end
end

# Commits per file over the last 90 days: the files people keep touching are where a fix pays off.
def churn(repo)
  log = `git -C #{repo.toplevel} log --since=90.days.ago --name-only --format= 2>/dev/null`
  prefix = repo.root.relative_path_from(repo.toplevel).to_s.then { it == "." ? "" : "#{it}/" }
  log.lines.map(&:strip).grep(/\A#{Regexp.escape(prefix)}/).map { it.delete_prefix(prefix) }.tally
end

# schema.rb and routes.rb churn with every migration and route, so their findings borrow
# the churn of the model or controller they're about.
def churned_paths(id, entry)
  case entry["check"]
  when "state-columns"
    model = id[/ (\w+)\./, 1].sub(/ies\z/, "y").delete_suffix("s")
    [ "app/models/#{model}.rb", "app/models/#{model.sub("_", "/")}.rb" ]
  when "custom-route"
    controller = entry["message"][/to:\s*["']([\w\/]+)#/, 1]
    controller ? [ "app/controllers/#{controller}_controller.rb" ] : []
  else
    [ entry["path"] ]
  end
end

def score(id, entry, churn)
  size = entry["check"] == "unorganized-model" ? entry["message"].to_i / 150.0 : 1
  commits = churned_paths(id, entry).sum { churn.fetch(it, 0) }
  WEIGHTS.fetch(entry["check"], 1) * (1 + commits) * size
end

def next_theme(ledger, limit)
  churn = churn(ledger.repo)
  ranked = ledger.open.map { |id, entry| [ id, entry, score(id, entry, churn).round(1) ] }.sort_by { -_3 }

  themes = ranked.group_by { _2["check"] }.transform_values { |group| group.sum(&:last).round(1) }.sort_by { -_2 }
  puts "Themes by total score (weight × (1 + 90-day commits) × size):"
  themes.each { |check, total| puts "   #{total.to_s.rjust(7)}  #{check} (#{ranked.count { _2["check"] == check }})" }

  theme, = themes.first
  check = CHECKS.find { it.name == theme }
  puts
  puts "Next theme: #{theme} — wiki/#{check.page}.md"
  puts "   #{check.question}"
  ranked.select { _2["check"] == theme }.first(limit).each do |id, entry, score|
    puts "   #{score.to_s.rjust(6)}  #{entry["path"]}  #{entry["message"]}"
  end
end

if __FILE__ == $0
  args = ARGV.dup
  limit = args.delete("--next") ? (args.find { it.match?(/\A\d+\z/) }&.then { args.delete(it).to_i } || 10) : nil

  repo = Repo.new(args.first || ".")
  ledger = Ledger.new(repo)

  if limit
    next_theme(ledger, limit)
  else
    changes = ledger.record(findings_in(repo))
    ledger.save

    puts "#{ledger.path}"
    puts "   new #{changes[:new].size}, reopened #{changes[:reopened].size}, fixed #{changes[:fixed].size}, open #{ledger.open.size}"
    changes.each do |kind, ids|
      ids.first(20).each { puts "   #{kind}: #{it}" } unless kind == :new && ids.size == ledger.open.size
    end
  end
end
